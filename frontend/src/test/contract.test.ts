import { describe, expect, it } from 'vitest'
import type { Recommendation } from '../types/api'
import { analytics, history, profile, run } from './helpers'
import health from './fixtures/health.json'

describe('API contract (fixtures generated by the real backend)', () => {
  it('has the fields the UI relies on', () => {
    const r: Recommendation = run.recommendations[0]
    expect(Object.keys(r.scores).sort()).toEqual(
      ['beginner_friendliness', 'experience_compatibility', 'overall', 'repository_activity', 'semantic_similarity', 'skill_compatibility'])
    expect(r.issue.url).toMatch(/^https:\/\/github\.com\//)
    expect(typeof r.explanation).toBe('string')
    expect(Array.isArray(r.matching_skills)).toBe(true)
    expect(Array.isArray(r.potential_skills_to_learn)).toBe(true)
    expect(Object.keys(run.weights).sort()).toEqual(['activity', 'beginner', 'experience', 'semantic', 'skill'])
  })
  it('profile, history, analytics and health shapes', () => {
    expect(profile.id).toBeGreaterThan(0)
    expect(history.items[0]).toHaveProperty('recommendation_count')
    expect(analytics.totals.recommendation_runs).toBeGreaterThan(0)
    expect(analytics.score_distribution).toHaveLength(5)
    expect(health.status).toBe('ok')
  })
})
